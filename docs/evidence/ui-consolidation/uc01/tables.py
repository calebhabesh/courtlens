import json, collections, sys
d = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'controls.json'))
# class -> kit target (component size [variant]); "—" means outside the kit (see spec)
MAP = {
 'stats-cell-button':'— table cell target','stats-compare-toggle':'— row checkbox (Checkbox)','table-sort-button':'— table header sort',
 'stats-icon-action':'IconButton xs ghost','button-small':'Button lg secondary','courtlens-nav-dropdown-btn':'— header nav (shell)',
 'stats-preset-tab':'Segmented sm','control-pill':'Chip md/sm/lg','ui-select':'Select lg','ui-segmented-item':'Segmented md/sm',
 'showcase-roster-item':'— listbox option','courtlens-search-pill':'— header search field (shell)','button-secondary':'Button lg secondary',
 'ui-date-trigger':'MenuTrigger lg (leading icon)','stats-tool-button':'IconButton md ghost','stats-footer-button':'Button xs ghost',
 'ui-why-summary':'Button xs ghost (summary)','ui-menu-trigger':'MenuTrigger','button':'Button lg secondary','stats-position-chip':'Chip lg',
 'ui-tab-trigger':'Segmented sm (tabs)','stats-help-button':'Button lg secondary','context-stepper-button':'IconButton lg (attached group)',
 'ui-popover-trigger':'MenuTrigger lg (attached group)','ui-input':'— Input','lookup-input':'— Input','entity-chip':'Chip lg removable',
 'stats-team-button':'MenuTrigger lg','player-career-expand':'IconButton xs ghost','feed-link-button':'— inline text action',
 'ui-button':'Button (same size)','<summary>':'— disclosure (Accordion)',
}
def key(c):
    cls=c['cls'].split()
    if not cls:
        par=c['parentCls'].split()
        return ('entity-chip' if 'entity-chip' in par else f"<{c['tag']}>")
    if cls[0]=='button':
        extra=[x for x in cls[1:] if x.startswith('button-')]
        return 'button'+(' '+' '.join(extra) if extra else '')
    if cls[0]=='ui-button':
        v=[x[10:] for x in cls if x.startswith('ui-button-')]
        ib=' icon' if 'ui-icon-button' in cls else ''
        return 'ui-button '+'/'.join(v)+ib
    return cls[0]
def kit(k, h, txt):
    if k.startswith('ui-button'):
        size={28:'xs',32:'sm',34:'sm*',36:'md',40:'lg'}.get(round(h),'?')
        var=k.split()[1].split('/')[0]
        return ('IconButton' if k.endswith('icon') else 'Button')+f' {size} {var}'
    if k.startswith('button'):
        size={28:'xs',32:'sm',36:'md',40:'lg'}.get(round(h),'lg')
        return f"Button {size} "+('primary' if 'primary' in k else 'secondary')
    if k=='ui-menu-trigger': return 'MenuTrigger '+{28:'xs',34:'sm*',36:'md',40:'lg'}.get(round(h),'?')
    if k=='control-pill': return 'Chip '+{32:'sm',36:'md',40:'lg'}.get(round(h),'?')
    if k=='ui-segmented-item': return 'Segmented '+{32:'sm',36:'md'}.get(round(h),'?')
    return MAP.get(k,'?')
out=[]
out.append('Generated by `tables.py` from `controls.json` (desktop 1440x900; phone 390x844, touch, DPR 2; dark scheme).\n')
out.append('Columns: n = visible instances; height desktop/phone in css px; padding is computed inline-start/end on the control (0 means the control centers its content without padding, for example icon-only or an inner wrapper); text = font-size/weight; icons = rendered svg widths. `sm*` marks the 34 px md-with-text bug (see spec).\n')
ph={p['page']:p for p in d['phone']}
for p in d['desktop']:
    rows=collections.OrderedDict()
    for c in p['controls']:
        k=key(c); h=round(c['h'],1)
        dims=(h,f"{c['pl']}/{c['pr']}".replace('px',''),f"{c['fs'].replace('px','')}/{c['fw']}",','.join(str(round(s['w'])) for s in c['svgs']) or '–')
        r=rows.setdefault((k,dims),{'n':0,'ex':c['text'][:28].replace('|','/')})
        r['n']+=1
    phone=collections.defaultdict(collections.Counter)
    for c in ph[p['page']]['controls']: phone[key(c)][round(c['h'],1)]+=1
    out.append(f"\n### {p['page']} (`{p['path'].split('?')[0]}`)\n")
    out.append('| Control class | n | Example | Desktop h | Phone h | Padding L/R | Text | Icons | Kit target |')
    out.append('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for (k,dims),r in rows.items():
        phs='/'.join(f"{int(x) if x==int(x) else x}" for x in sorted(phone[k])) or 'hidden'
        out.append(f"| `{k}` | {r['n']} | {r['ex']} | {dims[0]} | {phs} | {dims[1]} | {dims[2]} | {dims[3]} | {kit(k,dims[0],r['ex'])} |")
open('tables.md','w').write('\n'.join(out)+'\n')
