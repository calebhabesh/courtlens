"""Freeze v2 JSON Schema and TS from Pydantic; --check catches contract drift."""

import argparse
import json
from pathlib import Path
from typing import Any

from courtload.domain.hybrid_assistant import (
    DurableThreadHeader,
    DurableTurnRecord,
    HybridTurnRequest,
    HybridTurnResponse,
    ThreadHistoryPage,
    TurnHistoryPage,
    TurnStreamEvent,
)

SCHEMA_PATH = Path("docs/design/assistant-v2.schema.json")
TS_PATH = Path("dashboard/lib/assistant-v2.generated.ts")
MODELS = (
    HybridTurnRequest,
    HybridTurnResponse,
    DurableTurnRecord,
    DurableThreadHeader,
    ThreadHistoryPage,
    TurnHistoryPage,
    TurnStreamEvent,
)


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(item) for item in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", {})
            value_type = ts_type(additional) if isinstance(additional, dict) else "unknown"
            return f"Record<string, {value_type}>"
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  {json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};"
                for key, value in properties.items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate(models: tuple[type[Any], ...] = MODELS) -> tuple[str, str]:
    definitions: dict[str, Any] = {}
    roots = {}
    for model in models:
        schema = model.model_json_schema(mode="validation")
        for key, value in schema.pop("$defs", {}).items():
            if key in definitions and definitions[key] != value:
                raise ValueError(f"inconsistent definition: {key}")
            definitions[key] = value
        roots[model.__name__] = schema
    definitions.update(roots)
    schema_text = (
        json.dumps(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$defs": definitions,
                "oneOf": [{"$ref": f"#/$defs/{name}"} for name in roots],
            },
            indent=2,
        )
        + "\n"
    )
    ts = "// Generated by scripts/generate_hybrid_contract.py. Do not edit.\n"
    ts += "// Backend validators also enforce evidence, source, action and digest bindings.\n\n"
    ts += (
        "\n\n".join(
            f"export type {key} = {ts_type(value)};" for key, value in sorted(definitions.items())
        )
        + "\n"
    )
    return schema_text, ts


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    from courtload.domain.assistant_agent import (
        AgentHistoryPage,
        AgentTurnResponse,
        StoredTurnRecord,
    )

    schema, ts = generate()
    agent_schema, agent_ts = generate((AgentTurnResponse, StoredTurnRecord, AgentHistoryPage))
    for path, content in (
        (SCHEMA_PATH, schema),
        (TS_PATH, ts),
        (Path("docs/design/assistant-v3.schema.json"), agent_schema),
        (Path("dashboard/lib/assistant-v3.generated.ts"), agent_ts),
    ):
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"stale generated contract: {path}")
        else:
            path.write_text(content)
    print("v2 / v3 JSON Schema / TypeScript contracts match")


if __name__ == "__main__":
    main()
